"""Write KDE colours that Firefox cannot read for itself.

Inside its own pages Firefox replaces the window, text and button system
colours with fixed stand-ins (only the accent is real), so userContent.css
cannot follow the KDE scheme live the way userChrome.css does. KDE's focus
and hover decoration colours (the Oxygen focus ring and hover glow) are not
system colours at all. So the install, and the colour watcher, write the
current scheme's colours here, from kdeglobals or a .colors file, as
--ox-c-* variables.

The same goes for icons: those pages cannot load moz-icon:// images, so the
reader view's Oxygen icons are written as file:// URLs, as --ox-icon-*
variables. An icon that is not installed is left out, and the page keeps
Firefox's own.

  firefox_colors.py SCHEME OUT.css
"""
import glob
import os
import sys
import urllib.parse

here = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [here, os.path.join(here, "compare")]  # beside it in a package, in compare/ in the repo
import kdecolors  # noqa: E402

COLORS = {
    "bg": ("Window", "BackgroundNormal"),
    "fg": ("Window", "ForegroundNormal"),
    "base": ("View", "BackgroundNormal"),
    "text": ("View", "ForegroundNormal"),
    "btn": ("Button", "BackgroundNormal"),
    "btn-fg": ("Button", "ForegroundNormal"),
    "link": ("View", "ForegroundLink"),
    "visited": ("View", "ForegroundVisited"),
    "focus": ("Button", "DecorationFocus"),
    "hover": ("Button", "DecorationHover"),
}


# Variable name: (icon name, size) in the Oxygen icon theme.
ICONS = {
    "close": ("window-close", 22),
    "text": ("preferences-desktop-font", 22),
    "colors": ("preferences-desktop-color", 22),
    "listen": ("audio-headphones", 22),
    "minus": ("format-font-size-less", 16),
    "plus": ("format-font-size-more", 16),
    "left": ("format-justify-left", 16),
    "center": ("format-justify-center", 16),
    "right": ("format-justify-right", 16),
    "justify": ("format-justify-fill", 16),
}


def find_icon(name, size):
    data = [os.environ.get("XDG_DATA_HOME") or os.path.expanduser("~/.local/share")]
    data += (os.environ.get("XDG_DATA_DIRS") or "/usr/local/share:/usr/share").split(":")
    for d in [os.path.expanduser("~/.icons")] + [os.path.join(x, "icons") for x in data]:
        for sub in ("oxygen/base", "oxygen"):
            for path in glob.glob(os.path.join(d, sub, "%dx%d" % (size, size), "*", name + ".png")):
                return path
    return None


def main(scheme, out):
    color = kdecolors.load(scheme)
    lines = ["/* Generated by tools/firefox_colors.py from %s. */" % os.path.basename(scheme), ":root {"]
    for name, key in COLORS.items():
        lines.append("  --ox-c-%s: rgb(%d %d %d);" % ((name,) + color(*key)))
    for var, (name, size) in ICONS.items():
        path = find_icon(name, size)
        if path:
            lines.append('  --ox-icon-%s: url("file://%s");' % (var, urllib.parse.quote(path)))
    lines.append("}")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
